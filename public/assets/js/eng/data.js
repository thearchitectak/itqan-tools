// وزن المتر الطولي: كثافة الصلب 7850 كجم/م³ ⇐ 0.006165 × القطر² (بالمليمتر)
export function barKg(code, d) {
  const b = REBAR[code].bars.find(x => x.d === d);
  if (b?.kg) return b.kg;
  return 7850 * Math.PI / 4 * (d / 1000) ** 2;
}
export function barDia(code, d) { return REBAR[code].bars.find(x => x.d === d)?.dia || d; }

